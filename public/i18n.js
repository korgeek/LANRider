export function t(text, values = {}, language = locale) {
  const translated = language === 'ko' ? text : english[text] ?? text;
  return translated.replace(/\{(\w+)\}/g, (token, key) => Object.hasOwn(values, key) ? String(values[key]) : token);
}

// Called once before player names or room data enter the document.
export function localizeDocument(root = document) {
  root.documentElement.lang = locale;
  if (locale === 'ko') return;
  const walker = root.createTreeWalker(root.documentElement, 4);
  while (walker.nextNode()) {
    const node = walker.currentNode, source = node.textContent.trim();
    if (Object.hasOwn(english, source)) node.textContent = node.textContent.replace(source, english[source]);
  }
  for (const element of root.querySelectorAll('[aria-label], [placeholder]')) {
    for (const attribute of ['aria-label', 'placeholder']) {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute, t(element.getAttribute(attribute)));
    }
  }
}
